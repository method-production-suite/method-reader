//! Port of tests/update-compare-module.test.ts (9 checks): the comparator
//! the window runs must be the comparator the engine runs.
//!
//! The behavioural half needs a JavaScript runtime, so it runs through bun
//! (tests/data/compare-probe.ts asks one module every question) and skips,
//! saying so, where bun is absent. The engine's answers are also recorded in
//! tests/data/compare-answers.json, checked against the live engine whenever
//! bun is here, and that record is what sp-app's own comparator
//! (rust/crates/sp-app/src/model/update_compare.rs, compiled into this test
//! from its source) is held to on every platform, with or without bun.

#[path = "../../sp-app/src/model/update_compare.rs"]
#[allow(dead_code)]
mod sp_app_compare;

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::{Value, json};
use xtask::packaging::compare::{
    SOURCE, TARGET, TYPES_TARGET, build_argv, render_compare_module, render_compare_types,
};
use xtask::packaging::util::RunResult;
use xtask::paths::{bun, repo_root};

fn committed() -> Option<String> {
    fs::read_to_string(repo_root().join(TARGET)).ok()
}

fn bun_available() -> bool {
    Command::new(bun())
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success())
}

fn data(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/data")
        .join(name)
}

fn recorded() -> Value {
    serde_json::from_str(&fs::read_to_string(data("compare-answers.json")).unwrap()).unwrap()
}

/// The probe's answers for one module, through bun.
fn probe(module: &str) -> Value {
    let out = Command::new(bun())
        .arg(data("compare-probe.ts"))
        .arg(repo_root().join(module))
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    serde_json::from_slice(&out.stdout).unwrap()
}

