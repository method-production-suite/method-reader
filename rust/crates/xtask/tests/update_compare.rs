const PAIRS: [(&str, &str); 14] = [
    ("0.6.0", "0.6.0-1-g965cb10"),
    ("0.6.0", "0.6.0-1-g965cb10-dirty"),
    ("0.6.0", "0.6.0-dirty"),
    ("0.7.0", "0.6.0-1-g965cb10"),
    ("0.6.1", "0.6.0"),
    ("0.6.0", "0.6.0"),
    ("0.5.4", "0.6.0"),
    ("0.10.0", "0.9.0"),
    ("1.0.0", "0.99.99"),
    ("0.6.0", "0.6.0-beta.1"),
    ("0.6.0", "0.3.0-dev"),
    ("0.6.0-beta.10", "0.6.0-beta.9"),
    ("v0.4.0", "0.3.0"),
    ("0.3.0+ci.7", "0.3.0"),
];
const SUFFIXES: [&str; 6] = ["1-g965cb10", "dirty", "beta.1", "dev", "1-g", "x-g965cb10"];
const PICKS: [Option<(&str, &str)>; 5] = [
    None,
    Some(("0.7.0", "0.6.0")),
    Some(("0.6.0", "0.6.0-1-g965cb10")),
    Some(("not-a-version", "0.6.0")),
    Some(("0.6.0", "")),
];

#[test]
fn sp_app_answers_what_the_engine_answers() {
    use sp_app_compare::*;
    let r = recorded();
    let is_newer: Vec<Value> = PAIRS.iter().map(|(a, b)| json!(is_newer(a, b))).collect();
    assert_eq!(Value::Array(is_newer), r["isNewer"], "is_newer");
    let normalized: Vec<Value> = PAIRS
        .iter()
        .map(|(a, _)| json!(normalize_version(a)))
        .collect();
    assert_eq!(
        Value::Array(normalized),
        r["normalizeVersion"],
        "normalize_version"
    );
    let suffix: Vec<Value> = SUFFIXES
        .iter()
        .map(|s| json!(is_describe_suffix(s)))
        .collect();
    assert_eq!(
        Value::Array(suffix),
        r["isDescribeSuffix"],
        "is_describe_suffix"
    );
    let picks: Vec<Value> = PICKS
        .iter()
        .map(|c| match pick_update(*c) {
            Pick::Offer(v) => json!({"offer": true, "version": v}),
            Pick::No(reason) => json!({"offer": false, "reason": reason}),
        })
        .collect();
    assert_eq!(Value::Array(picks), r["pickUpdate"], "pick_update");
    let now = 1_800_000_000_000.0;
    let h = 3_600_000.0;
    let checks: Vec<Value> = [
        (false, None),
        (true, None),
        (true, Some(now - h)),
        (true, Some(now - 25.0 * h)),
        (true, Some(now + h)),
    ]
    .iter()
    .map(|(o, l)| json!(should_check(*o, *l, now)))
    .collect();
    assert_eq!(Value::Array(checks), r["shouldCheck"], "should_check");
    assert_eq!(json!(CHECK_INTERVAL_MS as u64), r["checkIntervalMs"]);
}
