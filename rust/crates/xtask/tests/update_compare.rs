#[test]
fn the_window_and_the_engine_agree_on_every_question_and_the_record_is_current() {
    if committed().is_none() || !bun_available() {
        eprintln!("skipped: needs bun and {TARGET}");
        return;
    }
    let engine = probe(SOURCE);
    assert_eq!(
        probe(TARGET),
        engine,
        "the window disagrees with the engine"
    );
    assert_eq!(
        recorded(),
        engine,
        "tests/data/compare-answers.json is stale: rerun the probe against {SOURCE}"
    );
}

#[test]
fn the_record_asks_questions_with_both_answers() {
    // Non-vacuity: an all-true or all-false comparison list tests nothing.
    let r = recorded();
    let answers = r["isNewer"].as_array().unwrap();
    assert!(answers.contains(&json!(true)));
    assert!(answers.contains(&json!(false)));
    assert_eq!(answers.len(), 14);
}

