#[test]
fn byte_for_byte() {
    let Some(file) = committed() else {
        eprintln!("skipped: {TARGET} is gone (cutover)");
        return;
    };
    if !bun_available() {
        eprintln!("skipped: no bun here to transpile {SOURCE}");
        return;
    }
    let built = render_compare_module(
        &repo_root(),
        &bun(),
        &mut |a: &[String], cwd: Option<&Path>| xtask::packaging::util::real_run(a, cwd),
    )
    .unwrap();
    assert_eq!(file, built);
}

#[test]
fn the_generator_adds_the_header_to_what_bun_printed_and_refuses_a_failed_build() {
    let mut seen = Vec::new();
    let out = render_compare_module(
        Path::new("/repo"),
        Path::new("bun"),
        &mut |a: &[String], cwd: Option<&Path>| {
            seen.push((a.to_vec(), cwd.map(Path::to_path_buf)));
            RunResult::ok("// src/update/compare.ts\nfunction f() {}\n")
        },
    )
    .unwrap();
    assert!(out.starts_with("// GENERATED by tools/build-update-compare.ts \u{2014} do not edit.\n// Source: src/update/compare.ts\n// Regenerate with: bun tools/build-update-compare.ts\n// src/update/compare.ts\n"));
    assert_eq!(seen[0].0, build_argv(Path::new("bun")));
    assert_eq!(seen[0].1.as_deref(), Some(Path::new("/repo")));
    assert!(build_argv(Path::new("bun")).contains(&"--target=browser".to_string()));
    assert!(build_argv(Path::new("bun")).contains(&"--format=esm".to_string()));
    assert!(
        !build_argv(Path::new("bun"))
            .iter()
            .any(|a| a.contains("minify"))
    );

    let err = render_compare_module(
        Path::new("/repo"),
        Path::new("bun"),
        &mut |_: &[String], _: Option<&Path>| RunResult {
            exit_code: 1,
            stdout: String::new(),
            stderr: "error: Could not resolve".into(),
        },
    )
    .unwrap_err();
    assert!(err.contains("Could not resolve"), "{err}");
}

