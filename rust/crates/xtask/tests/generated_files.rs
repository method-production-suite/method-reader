//! The files transitional TypeScript generators wrote into the Rust tree.
//!
//! Each generator reads the TypeScript engine or its dependencies (pdfjs-dist,
//! fountain-js), which go at cutover, so the generator goes too and the file
//! it wrote becomes the only copy (rust/PARITY.md, "## Tools"). These pin
//! each file by digest, so nothing edits one by hand or regenerates it from
//! a different pdf.js without the change showing here. A deliberate
//! regeneration before cutover updates the digest in the same commit.
//!
//! Line endings are normalized to LF first, so a Windows checkout that turns
//! them into CRLF hashes the same.

use sha2::{Digest, Sha256};
use xtask::paths;

fn digest(relative: &str) -> String {
    let path = paths::repo_root().join(relative);
    let bytes =
        std::fs::read(&path).unwrap_or_else(|e| panic!("{} is committed: {e}", path.display()));
    let mut lf = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'\r' && bytes.get(i + 1) == Some(&b'\n') {
            i += 1;
            continue;
        }
        lf.push(bytes[i]);
        i += 1;
    }
    Sha256::digest(&lf)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// (file, the generator that wrote it, its sha256 with LF line endings)
const PINNED: &[(&str, &str, &str)] = &[
    (
        "rust/crates/sp-pdf/src/tables.rs",
        "rust/crates/sp-pdf/oracle/gen-tables.ts (pdfjs-dist 6.3.289)",
        "e013e7b6aa1d044bf9e7c079f866ebad749bf09c97bb321052e62b0e5a75fdd3",
    ),
    (
        "rust/crates/sp-epub/tests/data/options-golden.json",
        "rust/crates/sp-epub/tests/data/options-golden.ts",
        "e4c215a38c693b66e76f72fda00c20c8a1b3d9c88f2d0f1f04b1f1ce4cf9d433",
    ),
    (
        "rust/crates/sp-mobi/tests/data/mobi-sources.json",
        "rust/crates/sp-mobi/tests/data/mobi-sources.ts",
        "5f3a1a3a476d2ee2c14bee815970f74f2e45fcd71f23a9dc697fb103acad0023",
    ),
    (
        "rust/crates/sp-fdx/tests/data/fountain-tokens.json",
        "rust/crates/sp-fdx/tests/data/record-tokens.ts",
        "534aa2c5b8f573753c9a7d960a0fc2c5192d42d78703f7031b03d15cecc02781",
    ),
];

#[test]
fn every_generated_file_is_the_one_its_generator_last_wrote() {
    let mut wrong = Vec::new();
    for (file, generator, want) in PINNED {
        let got = digest(file);
        if got != *want {
            wrong.push(format!(
                "{file} (from {generator}): sha256 {got}, pinned {want}"
            ));
        }
    }
    assert!(wrong.is_empty(), "{}", wrong.join("\n"));
}

#[test]
fn the_pdf_tables_still_say_where_they_came_from() {
    let text = std::fs::read_to_string(paths::repo_root().join(PINNED[0].0)).expect("tables.rs");
    assert!(text.starts_with(
        "// GENERATED by rust/crates/sp-pdf/oracle/gen-tables.ts from pdfjs-dist 6.3.289."
    ));
}
