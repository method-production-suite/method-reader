//! desktop/ui/update-compare.js, transpiled from src/update/compare.ts:
//! was tools/build-update-compare.ts.
//!
//! The webview has no build step and cannot import TypeScript, so the
//! engine's comparator reaches the window as a generated ES module: one
//! definition of the downgrade rule, mechanically copied. Transpiling
//! TypeScript is bun's job, so this runs `bun build` (`$BUN` or `bun` on
//! PATH), which prints exactly what the TypeScript's `Bun.build` call wrote,
//! and adds the same header. Retires at cutover with desktop/ui and
//! src/update/compare.ts: the native window carries the comparator itself
//! (sp-app's model/update_compare.rs), and tests/update_compare.rs holds
//! that copy to the TypeScript's answers until then.

use std::path::{Path, PathBuf};

use super::util::{RunResult, Runner, real_run};
use crate::paths::{bun, repo_root};

pub const SOURCE: &str = "src/update/compare.ts";
pub const TARGET: &str = "desktop/ui/update-compare.js";
pub const TYPES_TARGET: &str = "desktop/ui/update-compare.d.ts";

fn header() -> String {
    [
        "// GENERATED by tools/build-update-compare.ts \u{2014} do not edit.".to_string(),
        format!("// Source: {SOURCE}"),
        "// Regenerate with: bun tools/build-update-compare.ts".to_string(),
        String::new(),
    ]
    .join("\n")
}

/// The argv that transpiles the comparator: browser ES module, not
/// minified, because people read this file to answer a bug report.
pub fn build_argv(bun: &Path) -> Vec<String> {
    vec![
        bun.to_string_lossy().into_owned(),
        "build".into(),
        SOURCE.into(),
        "--target=browser".into(),
        "--format=esm".into(),
    ]
}

/// The generated module, from `bun build` run in `repo`.
pub fn render_compare_module(
    repo: &Path,
    bun: &Path,
    run: &mut Runner<'_>,
) -> Result<String, String> {
    let RunResult {
        exit_code,
        stdout,
        stderr,
    } = run(&build_argv(bun), Some(repo));
    if exit_code != 0 || stdout.trim().is_empty() {
        return Err(format!(
            "build-update-compare: expected exactly one output from {SOURCE}, got {}{}",
            if exit_code == 0 {
                "nothing"
            } else {
                "a failed build"
            },
            if stderr.trim().is_empty() {
                String::new()
            } else {
                format!("\n{}", stderr.trim())
            }
        ));
    }
    Ok(header() + &stdout)
}

/// The declaration beside it: a RE-EXPORT of the engine's own types, never
/// a written-out copy.
pub fn render_compare_types() -> String {
    header()
        + &[
            "// Not the generated JavaScript's types written out, but a re-export of",
            "// the engine module's. The claim is that these two have the same shape,",
            "// so the declaration says exactly that and cannot drift from it.",
            "export * from '../../src/update/compare';",
            "",
        ]
        .join("\n")
}

fn targets(repo: &Path) -> (PathBuf, PathBuf) {
    (repo.join(TARGET), repo.join(TYPES_TARGET))
}

/// `cargo xtask build-update-compare`.
pub fn main(args: &[String]) -> u8 {
    if let Some(a) = args.first() {
        if a == "-h" || a == "--help" {
            println!(
                "usage: cargo xtask build-update-compare\n\nRegenerates {TARGET} and {TYPES_TARGET} from {SOURCE} (needs bun, or $BUN)."
            );
            return 0;
        }
        eprintln!("build-update-compare: unexpected argument {a}");
        return 2;
    }
    let repo = repo_root();
    let module = match render_compare_module(&repo, &bun(), &mut real_run) {
        Ok(m) => m,
        Err(e) => {
            eprintln!("{e}");
            return 1;
        }
    };
    let (js, dts) = targets(&repo);
    if let Err(e) =
        std::fs::write(&js, module).and_then(|()| std::fs::write(&dts, render_compare_types()))
    {
        eprintln!("build-update-compare: {e}");
        return 1;
    }
    println!("wrote {TARGET} and {TYPES_TARGET} from {SOURCE}");
    0
}
