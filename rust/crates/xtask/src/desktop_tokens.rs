//! `cargo xtask build-desktop-tokens`: was tools/build-desktop-tokens.ts.
//!
//! desktop/ui/tokens.css, generated from brand/tokens.json and the scale
//! blocks of brand/tokens.css. desktop/ui has no build step and Tauri embeds
//! only what is under desktop/ui/, so the window needs a copy; this makes
//! sure nobody maintains it by hand.
//!
//! The seven colours in [`CORE_IN_STYLE_CSS`] are deliberately EXCLUDED:
//! they live in desktop/ui/style.css. Declaring them twice would create a
//! "which block wins" question with no good answer.
//!
//! The output is byte for byte what the TypeScript wrote, header included,
//! so desktop.yml's `git diff --exit-code` holds whichever of the two ran.
//! Retires at cutover with desktop/ui: the egui window reads its colours
//! from sp-app's theme.rs, which `tests/desktop_tokens.rs` checks against
//! brand/tokens.json directly.

use std::path::Path;

use serde_json::Value;

use crate::paths::repo_root;

/// The colours desktop/ui/style.css declares itself.
pub const CORE_IN_STYLE_CSS: [&str; 7] = [
    "paper",
    "ink",
    "ink-muted",
    "ink-on-brass",
    "brass",
    "ground",
    "alarm",
];

const HEADER: &str = "/* GENERATED by tools/build-desktop-tokens.ts \u{2014} do not edit.
 * Source of truth: brand/tokens.json (colours) and brand/tokens.css (scales).
 * The seven colours desktop/ui/style.css declares are excluded on purpose;
 * see the generator for why. Regenerate with:
 *   bun tools/build-desktop-tokens.ts
 */
";

/// The non-colour blocks lifted verbatim from brand/tokens.css, each named
/// by a declaration that opens it there.
const SCALE_MARKERS: [&str; 6] = [
    "--font-structure:",
    "--text-fine:",
    "--radius-mark:",
    "--motion-press:",
    "--space-1:",
    "--measure:",
];

/// `--name: value;` at the start of a trimmed line, up to the FIRST `;`
/// (several declarations carry a trailing comment after it): the name.
fn declared_name(declaration: &str) -> Option<&str> {
    let rest = declaration.strip_prefix("--")?;
    let colon = rest.find(':')?;
    let name = &rest[..colon];
    if name.is_empty()
        || !name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    {
        return None;
    }
    // `\s*(.+?);` needs at least one character, space or not, before the
    // first semicolon.
    let semi = rest[colon + 1..].find(';')?;
    (semi > 0).then_some(name)
}

fn scale_lines(brand_css: &str, color_names: &[String]) -> Result<Vec<String>, String> {
    let start = brand_css.find(":root").unwrap_or(0);
    let end = brand_css.find("@media").unwrap_or(brand_css.len());
    let root = brand_css.get(start..end.max(start)).unwrap_or("");
    let mut lines = Vec::new();
    for line in root.split('\n') {
        let declaration = line.trim();
        let Some(name) = declared_name(declaration) else {
            continue;
        };
        // Colours come from tokens.json. Matched by EXACT name: `--hole` is a
        // colour and `--hole-center` is geometry.
        if color_names.iter().any(|c| c == name) {
            continue;
        }
        lines.push(format!("  {declaration}"));
    }
    for marker in SCALE_MARKERS {
        if !lines.iter().any(|l| l.contains(marker)) {
            return Err(format!("brand/tokens.css no longer declares {marker}"));
        }
    }
    Ok(lines)
}

/// The colours of brand/tokens.json, in file order: (name, light, dark).
pub fn brand_colors(tokens_json: &str) -> Result<Vec<(String, String, String)>, String> {
    let parsed: Value =
        serde_json::from_str(tokens_json).map_err(|e| format!("brand/tokens.json: {e}"))?;
    let colors = parsed
        .get("colors")
        .and_then(Value::as_object)
        .ok_or("brand/tokens.json has no colors object")?;
    colors
        .iter()
        .map(|(name, c)| {
            let mode = |m: &str| {
                c.get(m)
                    .and_then(Value::as_str)
                    .map(str::to_string)
                    .ok_or_else(|| format!("brand/tokens.json: {name} has no {m} value"))
            };
            Ok((name.clone(), mode("light")?, mode("dark")?))
        })
        .collect()
}

/// desktop/ui/tokens.css for these two sources.
pub fn build_desktop_tokens(tokens_json: &str, brand_css: &str) -> Result<String, String> {
    let colors = brand_colors(tokens_json)?;
    let kept: Vec<&(String, String, String)> = colors
        .iter()
        .filter(|(n, _, _)| !CORE_IN_STYLE_CSS.contains(&n.as_str()))
        .collect();
    let light: Vec<String> = kept
        .iter()
        .map(|(n, l, _)| format!("  --{n}: {l};"))
        .collect();
    let dark: Vec<String> = kept
        .iter()
        .filter(|(_, l, d)| d != l)
        .map(|(n, _, d)| format!("    --{n}: {d};"))
        .collect();
    let names: Vec<String> = colors.iter().map(|(n, _, _)| n.clone()).collect();
    let scales = scale_lines(brand_css, &names)?;
    Ok(format!(
        "{HEADER}\n:root {{\n{}\n\n{}\n}}\n\n@media (prefers-color-scheme: dark) {{\n  :root {{\n{}\n  }}\n}}\n",
        light.join("\n"),
        scales.join("\n"),
        dark.join("\n"),
    ))
}

/// The generator over a repository's own files.
pub fn render_for_repo(repo: &Path) -> Result<String, String> {
    let read = |p: &str| {
        std::fs::read_to_string(repo.join(p)).map_err(|e| format!("cannot read {p}: {e}"))
    };
    build_desktop_tokens(&read("brand/tokens.json")?, &read("brand/tokens.css")?)
}

/// `cargo xtask build-desktop-tokens`: its exit code.
pub fn main(args: &[String]) -> u8 {
    if args.iter().any(|a| a == "-h" || a == "--help") {
        println!(
            "usage: cargo xtask build-desktop-tokens\n\nRegenerates desktop/ui/tokens.css from brand/tokens.json and brand/tokens.css."
        );
        return 0;
    }
    if let Some(extra) = args.first() {
        eprintln!("build-desktop-tokens: unexpected argument {extra}");
        return 2;
    }
    let repo = repo_root();
    match render_for_repo(&repo) {
        Ok(out) => match std::fs::write(repo.join("desktop/ui/tokens.css"), out) {
            Ok(()) => {
                println!("wrote desktop/ui/tokens.css");
                0
            }
            Err(e) => {
                eprintln!("build-desktop-tokens: cannot write desktop/ui/tokens.css: {e}");
                1
            }
        },
        Err(e) => {
            eprintln!("build-desktop-tokens: {e}");
            1
        }
    }
}
